"""
End-to-end run: data -> rolling backtest -> forecast -> results, dashboard, README.

    python -m oilcast.run                 # real Brent data (FRED; cached in data/)
    python -m oilcast.run --refresh       # re-download from FRED
    python -m oilcast.run --synthetic     # offline demo on the synthetic series (clearly labelled)
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

from .backtest import rolling_backtest
from .data import data_source, load_brent
from .models import MODEL_BY_NAME, Naive

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def best_model(bt: dict, horizon: str = "1") -> str:
    """Lowest out-of-sample RMSE at the given horizon (ties -> simpler model: naive first)."""
    return min(bt["models"], key=lambda m: (bt["models"][m]["horizons"][horizon]["rmse"], m != Naive.name))


def to_markdown(res: dict) -> str:
    bt = res["backtest"]
    hs = bt["horizons"]
    lines = [f"**Data:** {res['data']['source']}, {res['data']['start']} to {res['data']['end']} "
             f"({res['data']['n']} months). **Backtest:** {bt['n_origins']} rolling origins, expanding window, "
             f"run {res['run_at'][:10]}.", "",
             "Out-of-sample RMSE (USD/bbl) by horizon; in brackets: RMSE relative to the naive random walk "
             "(<1 = better). ✓ = significantly better than naive (Diebold-Mariano, p<0.05).", "",
             "| Model | " + " | ".join(f"h={h}" for h in hs) + " |", "|---|" + "---|" * len(hs)]
    for m, v in bt["models"].items():
        cells = []
        for h in hs:
            r = v["horizons"][str(h)]
            rel = r.get("rel_rmse_vs_naive")
            sig = " ✓" if r.get("dm_stat") is not None and r.get("dm_stat", 0) < 0 and r.get("p_value", 1) < 0.05 else ""
            cells.append(f"{r['rmse']:.2f}" + (f" ({rel:.2f}){sig}" if rel is not None else ""))
        lines.append(f"| {m} | " + " | ".join(cells) + " |")
    f = res["forecast"]
    lines += ["", f"**Best 1-month model out of sample:** {res['best_model_h1']}. "
              f"Next-month forecast ({f['dates'][0]}): ${f['values'][0]:.2f}/bbl.", ""]
    return "\n".join(lines)


def update_readme(md: str):
    p = ROOT / "README.md"
    s = p.read_text(encoding="utf-8")
    if START in s:
        s = s[:s.index(START) + len(START)] + "\n" + md + "\n" + s[s.index(END):]
        p.write_text(s, encoding="utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--refresh", action="store_true")
    ap.add_argument("--synthetic", action="store_true")
    ap.add_argument("--start", default="2000-01-01")
    ap.add_argument("--origins", type=int, default=60)
    ap.add_argument("--horizon", type=int, default=12)
    a = ap.parse_args(argv)

    if a.synthetic:
        from .ar12_model import generate_brent_oil_series
        df = generate_brent_oil_series(n_months=240, seed=42)
        source = "SYNTHETIC series generated by an AR(12) process (demo only, not real prices)"
    else:
        df = load_brent(refresh=a.refresh, start=a.start)
        source = data_source()
    y = df["brent_usd"].to_numpy(dtype=float)

    bt = rolling_backtest(y, n_origins=a.origins)
    best = best_model(bt)
    fc = MODEL_BY_NAME[best]().fit(y).forecast(a.horizon)
    dates = pd.date_range(df["date"].iloc[-1] + pd.DateOffset(months=1), periods=a.horizon, freq="MS")
    res = {"run_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
           "data": {"source": source, "synthetic": a.synthetic, "n": len(df),
                    "start": df["date"].iloc[0].strftime("%Y-%m"), "end": df["date"].iloc[-1].strftime("%Y-%m")},
           "backtest": bt, "best_model_h1": best,
           "forecast": {"model": best, "dates": [d.strftime("%Y-%m") for d in dates],
                        "values": [round(float(v), 2) for v in fc]}}

    RESULTS.mkdir(exist_ok=True)
    stem = "backtest_synthetic" if a.synthetic else "backtest"
    (RESULTS / f"{stem}.json").write_text(json.dumps(res, indent=2))
    md = to_markdown(res)
    (RESULTS / f"{stem}.md").write_text(md)

    from .dashboard import export_comparison_dashboard
    export_comparison_dashboard(df, res, str(ROOT / "output" / ("dashboard_synthetic.html" if a.synthetic else "dashboard.html")))
    if not a.synthetic:
        update_readme(md)
    print(md)
    return res


if __name__ == "__main__":
    main()
